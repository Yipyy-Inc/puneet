-- ── Who is the caller, as a customer? ───────────────────────────────────────
-- SECURITY DEFINER so it can read clients while clients' own policies are
-- being evaluated, and in `private` so it is not exposed as an RPC — a
-- client-callable function that returns ids is a discovery tool.
create or replace function private.own_client_ids()
returns setof uuid
language sql
stable
security definer
set search_path = ''
as $$
  select c.id from public.clients c where c.profile_id = (select auth.uid());
$$;

-- `authenticated` must be granted EXPLICITLY. Revoking from PUBLIC also
-- removes what authenticated inherits through it, and every policy calling
-- this then fails with "permission denied for function own_client_ids" — which
-- surfaces as a customer being unable to read their own pets. What keeps the
-- function away from clients is that `private` is not an exposed PostgREST
-- schema, not the absence of a grant.
grant execute on function private.own_client_ids() to authenticated;
revoke execute on function private.own_client_ids() from anon;

-- ── RLS ─────────────────────────────────────────────────────────────────────
-- Two audiences per table, and they are not symmetrical:
--   staff     — permission-gated, scoped to facilities they belong to
--   customers — their own records only, no permission needed
--
-- auth.uid() is wrapped in (select …) so Postgres evaluates it once per query
-- rather than once per row (the auth_rls_initplan advisory).
-- Writes are split into insert/update/delete rather than `for all`, so a
-- read-only grant cannot accidentally carry write rights.

alter table public.clients      enable row level security;
alter table public.pets         enable row level security;
alter table public.bookings     enable row level security;
alter table public.booking_pets enable row level security;

-- Clients
create policy clients_read on public.clients
  for select to authenticated
  using (
    private.is_platform_admin()
    or profile_id = (select auth.uid())
    or private.has_permission(facility_id, 'view_clients')
  );

create policy clients_insert on public.clients
  for insert to authenticated
  with check (private.has_permission(facility_id, 'create_clients'));

create policy clients_update on public.clients
  for update to authenticated
  using (
    profile_id = (select auth.uid())
    or private.has_permission(facility_id, 'edit_clients')
  )
  with check (
    profile_id = (select auth.uid())
    or private.has_permission(facility_id, 'edit_clients')
  );

create policy clients_delete on public.clients
  for delete to authenticated
  using (private.has_permission(facility_id, 'delete_clients'));

-- Pets
create policy pets_read on public.pets
  for select to authenticated
  using (
    private.is_platform_admin()
    or client_id in (select private.own_client_ids())
    or private.has_permission(facility_id, 'view_pet_records')
  );

create policy pets_insert on public.pets
  for insert to authenticated
  with check (
    client_id in (select private.own_client_ids())
    or private.has_permission(facility_id, 'edit_pet_records')
  );

create policy pets_update on public.pets
  for update to authenticated
  using (
    client_id in (select private.own_client_ids())
    or private.has_permission(facility_id, 'edit_pet_records')
  )
  with check (
    client_id in (select private.own_client_ids())
    or private.has_permission(facility_id, 'edit_pet_records')
  );

create policy pets_delete on public.pets
  for delete to authenticated
  using (private.has_permission(facility_id, 'edit_pet_records'));

-- Bookings
create policy bookings_read on public.bookings
  for select to authenticated
  using (
    private.is_platform_admin()
    or client_id in (select private.own_client_ids())
    or private.has_permission(facility_id, 'view_bookings')
  );

-- A customer booking for themselves is a real path, so the check is "is this
-- your own client record" OR the staff permission — not staff-only.
create policy bookings_insert on public.bookings
  for insert to authenticated
  with check (
    client_id in (select private.own_client_ids())
    or private.has_permission(facility_id, 'create_bookings')
  );

create policy bookings_update on public.bookings
  for update to authenticated
  using (private.has_permission(facility_id, 'edit_bookings'))
  with check (private.has_permission(facility_id, 'edit_bookings'));

-- No delete policy, deliberately: bookings are cancelled, not deleted. Status
-- carries that, and the financial and no-show history has to survive it.

-- Booking ↔ pets: inherits the booking's visibility rather than restating it,
-- so the two can never disagree.
create policy booking_pets_read on public.booking_pets
  for select to authenticated
  using (exists (select 1 from public.bookings b where b.id = booking_id));

create policy booking_pets_insert on public.booking_pets
  for insert to authenticated
  with check (exists (select 1 from public.bookings b where b.id = booking_id));

create policy booking_pets_delete on public.booking_pets
  for delete to authenticated
  using (exists (select 1 from public.bookings b where b.id = booking_id));

-- Caught by the performance advisor after the fact: without this, deleting or
-- re-pointing a location sequentially scans every booking.
create index bookings_location_idx on public.bookings (location_id)
  where location_id is not null;
